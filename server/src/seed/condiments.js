/**
 * 展开成扁平的 seed 数组。
 * 元组位置：[id, name, shortName, glyph, defaultAmount, unitHint,
 *           flavorTags, spicyWeight, saltyWeight, richWeight, caution?, isAllergen?]
 */
export const SEED_CONDIMENTS = Object.entries(RAW).flatMap(([category, rows]) =>
  rows.map((r, indexInCategory) => ({
    id: r[0],
    name: r[1],
    short_name: r[2],
    glyph: r[3],
    category,
    // 同一幕内按数组顺序排 —— 顺序是照着调料台从前往后的物理摆位编的
    sort_order: indexInCategory * 10,
    default_amount: r[4],
    unit_hint: r[5],
    flavor_tags: JSON.stringify(r[6]),
    spicy_weight: r[7],
    salty_weight: r[8],
    rich_weight: r[9],
    caution: r[10] ?? '',
    is_allergen: r[11] ?? 0,
  })),
)

export default SEED_CONDIMENTS
